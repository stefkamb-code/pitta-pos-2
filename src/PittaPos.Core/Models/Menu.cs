namespace PittaPos.Core.Models;

/// <summary>Κατηγορία μενού (ΠΙΤΤΕΣ, ΜΕΡΙΔΕΣ, …). Επεξεργάσιμη από τη Διαχείριση Καταλόγου.</summary>
public class MenuCategory
{
    public required string Id { get; set; }
    public required string Name { get; set; }
    public List<Product> Products { get; set; } = [];

    // Οι τρεις παρακάτω συμπεριφορές είναι ΙΔΙΟΤΗΤΕΣ ΤΗΣ ΚΑΤΗΓΟΡΙΑΣ, όχι του ονόματός της. Παλιότερα
    // κρίνονταν συγκρίνοντας κυριολεκτικά το όνομα (π.χ. == "ΤΥΛΙΧΤΑ") — έτσι, μόλις το μαγαζί
    // μετονόμασε την κατηγορία σε «ΠΙΤΤΕΣ», έπαψαν σιωπηλά να δουλεύουν η επιλογή ψωμιού και η διπλή
    // πίτα σε ΟΛΑ τα προϊόντα της, χωρίς κανένα μήνυμα. Τώρα αποθηκεύονται μέσα στο menu.json και
    // ρυθμίζονται από τη Διαχείριση Καταλόγου, οπότε η μετονομασία δεν σπάει πια τίποτα.
    // null = δεν έχει αποφασιστεί ακόμα· το MenuStore το γεμίζει μία φορά από τους παλιούς κανόνες
    // ονόματος (βλ. MenuSeed/MenuStore.MigrateCategoryFlags), ώστε να μην αλλάξει τίποτα σε υπάρχοντα
    // καταστήματα.

    /// <summary>Αν τα προϊόντα της κατηγορίας ρωτούν ψωμί (Ελληνική/Αραβική/Ψωμί) στον customizer.</summary>
    public bool? HasBread { get; set; }

    /// <summary>Αν το ψωμί μπαίνει μέσα στο όνομα («ΑΡ. Κοτόπουλο») αντί σε ξεχωριστή γραμμή από κάτω.</summary>
    public bool? FuseBreadIntoName { get; set; }

    /// <summary>Αν προσφέρεται η επιλογή «διπλή πίτα».</summary>
    public bool? SupportsDoublePita { get; set; }

    /// <summary>
    /// Μεγάλη ή μικρή πίτα. Το μαγαζί έχει ΔΥΟ πίτες, όχι μία ανά κατηγορία: η χρέωση της διπλής
    /// κρέμεται από το μέγεθος, ώστε τρεις κατηγορίες μεγάλης πίτας να μοιράζονται μία τιμή αντί να
    /// γεννούν τρεις γραμμές χρέωσης που πρέπει να μένουν συγχρονισμένες με το χέρι.
    /// null = δεν έχει αποφασιστεί· το MenuStore το μαντεύει από το όνομα (ΜΙΚΡΑ/ΜΙΝΙ → μικρή).
    /// </summary>
    public bool? DoublePitaLarge { get; set; }

    /// <summary>Σε ποια κατηγορία ΦΠΑ ανήκουν τα προϊόντα της — βλ. <see cref="Models.VatKind"/>.
    /// null = δεν έχει αποφασιστεί, το MenuStore το μαντεύει από το όνομα (ίδια λογική με τα παραπάνω).</summary>
    public VatKind? VatKind { get; set; }

    /// <summary>Αν η κατηγορία στέλνεται στο e-food μαζί με τον κατάλογο (βλ. Efood.EfoodCatalogBuilder). Σβηστό σε
    /// ό,τι δεν είναι για πελάτες — π.χ. ΠΡΟΣΩΠΙΚΟ, που δεν έχει καμία σχέση με το e-food.
    /// null = δεν έχει αποφασιστεί, το MenuStore το μαντεύει από το όνομα (ίδια λογική με τα παραπάνω).</summary>
    public bool? OnEfood { get; set; }
}

/// <summary>
/// Πώς φορολογείται μια κατηγορία. Ο κανόνας του μαγαζιού είναι δεδομένος και δεν αλλάζει:
/// φαγητό 13%, ποτά (μπύρες/κρασιά/οινοπνευματώδη) 24% πάντα, και τα ΑΝΑΨΥΚΤΙΚΑ 13% — <b>εκτός στο
/// ΤΡΑΠΕΖΙ, όπου πάνε κι αυτά 24%</b> (σερβίρονται στον χώρο).
/// </summary>
public enum VatKind
{
    /// <summary>Φαγητό — 13% παντού.</summary>
    Food,
    /// <summary>Αναψυκτικά — 13%, αλλά 24% όταν είναι τραπέζι.</summary>
    SoftDrink,
    /// <summary>Ποτά — 24% παντού.</summary>
    Alcohol,
}

public class Product
{
    public required string Id { get; set; }
    public required string Name { get; set; }
    /// <summary>Προαιρετικό αγγλικό όνομα (δεύτερη γραμμή στο tile).</summary>
    public string? NameEn { get; set; }

    /// <summary>
    /// Όνομα ΜΟΝΟ για το χαρτί. Κενό ή null σημαίνει «τύπωσε ό,τι λέει και η οθόνη».
    ///
    /// Υπάρχει γιατί τα δύο κοινά δεν είναι ίδια: στην οθόνη ο ταμίας θέλει το πλήρες όνομα για να
    /// μην μπερδέψει δύο παρόμοια προϊόντα, ενώ στην απόδειξη μετράει το σύντομο που καταλαβαίνει ο
    /// ψήστης — και το χαρτί έχει μόλις 80mm πλάτος.
    /// </summary>
    public string? PrintName { get; set; }

    /// <summary>Το όνομα που πρέπει να τυπωθεί: το ειδικό αν έχει οριστεί, αλλιώς το κανονικό.</summary>
    public string NameForPrint => string.IsNullOrWhiteSpace(PrintName) ? Name : PrintName!;
    /// <summary>Περιγραφή/υλικά όπως στον κατάλογο.</summary>
    public string? Description { get; set; }
    /// <summary>Κανονική τιμή (όρθιο/τραπέζι/διανομή).</summary>
    public decimal Price { get; set; }
    /// <summary>Τιμή εφαρμογών (e-food/Wolt/BOX) — null = ίδια με την κανονική.</summary>
    public decimal? DeliveryPrice { get; set; }
    /// <summary>Αν ανοίγει customizer (ψωμί/υλικά/έξτρα) — «με τα υλικά της επιλογής σας».</summary>
    public bool Customizable { get; set; }
    /// <summary>Ονόματα από το κοινό MenuSeed.Extras που επιτρέπονται σε αυτό το προϊόν — null = όλα
    /// (προεπιλογή, ώστε παλιά προϊόντα να μη χάσουν έξτρα όταν προστέθηκε αυτό το πεδίο).</summary>
    public List<string>? ExtraNames { get; set; }

    /// <summary>
    /// Τα βασικά υλικά που έχει ΜΕΣΑ το προϊόν — αυτά που ξετσεκάρει ο ταμίας για να βγει «χωρίς
    /// κρεμμύδι». null = ο κοινός κατάλογος υλικών, όπως δούλευε πάντα.
    ///
    /// Πριν ήταν μία σταθερή λίστα για ΟΛΑ τα προϊόντα, γραμμένη μέσα στον κώδικα: η ομελέτα έδειχνε
    /// «χωρίς κρεμμύδι» ακόμα κι αν δεν είχε, και ένα νέο προϊόν δεν μπορούσε να δηλώσει τα δικά του.
    /// </summary>
    public List<string>? Ingredients { get; set; }

    /// <summary>
    /// Πόση α' ύλη φεύγει από την αποθήκη με ΕΝΑ τεμάχιο αυτού του προϊόντος — βλ.
    /// <see cref="MaterialUse"/>. null ή άδειο = δεν έχει δηλωθεί, το προϊόν δεν μετράει πουθενά.
    /// </summary>
    public List<MaterialUse>? Materials { get; set; }
}

/// <summary>
/// Πόσο και τι «κοστίζει σε υλικό» ένα τεμάχιο — π.χ. μια μεγάλη πίττα κοτόπουλο τρώει 100 γρ.
/// κοτόπουλο, ένα καλαμάκι 110 γρ. χοιρινό (και η μεγάλη πίττα έχει δύο μέσα, άρα 220).
///
/// <para><b>Γραμμάρια και όχι κιλά</b>: έτσι τα λέει το μαγαζί («η μικρή έχει 60»), και ο ταμίας
/// γράφει «60» αντί για «0,06» — τα κιλά βγαίνουν μόνο στο σύνολο της ημέρας.</para>
/// </summary>
public class MaterialUse
{
    /// <summary>Τι είναι — «Κοτόπουλο», «Χοιρινό», «Γύρος». Ελεύθερο κείμενο, με προτάσεις από ό,τι
    /// έχει ήδη γραφτεί αλλού, ώστε να μη γεννιούνται «Κοτοπουλο» και «Κοτόπουλο» χωριστά.</summary>
    public required string Name { get; set; }

    /// <summary>Γραμμάρια ανά ΕΝΑ τεμάχιο.</summary>
    public double Grams { get; set; }
}

/// <summary>Έξτρα υλικό με τιμή (0 = δωρεάν). Επεξεργάσιμο από τη Διαχείριση Καταλόγου.</summary>
public class ExtraItem
{
    public required string Name { get; init; }
    public decimal Price { get; set; }

    /// <summary>Τι τρώει από την αποθήκη το ίδιο το έξτρα. Χωρίς αυτό, ένα «έξτρα κοτόπουλο» δεν
    /// μετριόταν πουθενά και το σύνολο της ημέρας έβγαινε λιγότερο από την αλήθεια.</summary>
    public List<MaterialUse>? Materials { get; set; }
}
